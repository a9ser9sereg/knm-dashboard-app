#!/bin/bash
# Хук Stop: сохраняет правки памяти, сделанные в облачной сессии.
#
# ЗАЧЕМ. Облачное окружение живёт до конца сессии: незакоммиченные правки волта
# пропадают вместе с контейнером. Правило «в облаке коммить и пушь волт сам»
# записано в CLAUDE.md, но держится на внимании — забыть его нечем.
# Хук делает это механикой: после каждого хода правки уезжают в репозиторий.
#
# Локальный волт на Mac хук не трогает: там коммитит фоновый агент, и лезть
# туда со своими коммитами значит драться с ним за одни и те же файлы.
#
# Всегда завершается успешно: сорванный push не должен мешать работе — о нём
# просто будет сказано в выводе.
set -uo pipefail

VAULT_TMP="${KNM_VAULT_TMP:-/tmp/knm-vault}"

[ "$(uname)" = "Darwin" ] && exit 0
[ -d "$VAULT_TMP/.git" ] || exit 0

if [ -z "$(git -C "$VAULT_TMP" status --porcelain)" ]; then
  exit 0
fi

git -C "$VAULT_TMP" add -A
git -C "$VAULT_TMP" \
  -c user.name="Claude" \
  -c user.email="claude@knm-dashboard-app.local" \
  commit --quiet -m "память: правки из облачной сессии $(date +%F)" || exit 0

if git -C "$VAULT_TMP" push --quiet 2>/dev/null; then
  echo "Правки памяти закоммичены и запушены в волт."
else
  echo "⚠️ Правки памяти закоммичены в $VAULT_TMP, но push не прошёл."
  echo "Скажи об этом Алексею: с концом сессии контейнер (и коммит) пропадёт."
fi
exit 0
